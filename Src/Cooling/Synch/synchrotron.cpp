/*!
  \file
  \brief Synchrotron cooling source term.

  This module implements analytic synchrotron cooling in the fluid-rest
  frame using the non-dimensional form:
  \f[ \frac{dp}{dt} = -(\Gamma-1)\,C_{synch}\,\frac{B^2 p^2}{\rho} \f]
  where the coefficient is computed from c.g.s. constants and code units.

  The magnetic field is taken from the primitive variables in the fluid
  rest frame as \c B^2 = Bx^2 + By^2 + Bz^2.

  \authors Generated by code assistant
  \date    Jun 15, 2026
*/
/* ///////////////////////////////////////////////////////////////////// */
#include "gpluto.hpp"

#if !(PHYSICS == MHD || PHYSICS == RMHD || PHYSICS == ResRMHD)
#error "SYNCH cooling requires MHD or RMHD physics"
#endif

/* ********************************************************************* */
void SynchrotronCooling (Data &data, double dt, timeStep &Dts, Grid &grid)
{
  int i, j, k;
  double rho, p, p_f, T,T_f,B2, dE;
  const Ary4D &Vc = data.Vc;
  double g_gamma = data.run_config->gamma;

  double cost = CONST_sigmaT*CONST_mp;
  cost /= 2.0*CONST_PI*CONST_me*CONST_me*CONST_c*CONST_c*CONST_c;
  cost *= 4.0*CONST_PI*UNIT_DENSITY*UNIT_VELOCITY*UNIT_VELOCITY*UNIT_VELOCITY*UNIT_LENGTH;
  cost *= (g_gamma - 1.0);

  dE = 1.e-18;

  RBox box;
  box.ibeg = grid.gbeg[0];
  box.jbeg = grid.gbeg[1];
  box.kbeg = grid.gbeg[2];

  box.iend = grid.gend[0];
  box.jend = grid.gend[1];
  box.kend = grid.gend[2];

  BOX_LOOP(box,k,j,i){
    rho = Vc(i,j,k,RHO);
    p   = Vc(i,j,k,PRS);

    T = p/rho*(5.4e12*0.5);
    if (T < data.run_config->minCoolingTemp) continue;

    B2 = Vc(i,j,k,BX1)*Vc(i,j,k,BX1)
       + Vc(i,j,k,BX2)*Vc(i,j,k,BX2)
       + Vc(i,j,k,BX3)*Vc(i,j,k,BX3);

#if (PHYSICS == RMHD || PHYSICS == ResRMHD)
    double lor2 = 1.0/(1.0 - (Vc(i,j,k,VX1)*Vc(i,j,k,VX1)
                              + Vc(i,j,k,VX2)*Vc(i,j,k,VX2)
                              + Vc(i,j,k,VX3)*Vc(i,j,k,VX3)));
    B2 = B2/lor2 + pow(Vc(i,j,k,VX1)*Vc(i,j,k,BX1)
                     +Vc(i,j,k,VX2)*Vc(i,j,k,BX2)
                     +Vc(i,j,k,VX3)*Vc(i,j,k,BX3),2.0);
#endif

    p_f  = 1.0/p + cost*B2*dt/rho;
    p_f  = 1.0/p_f;
    p_f  = MAX(p_f, 0.0);

    T_f = p_f/rho*(5.4e12*0.5);
    if (T_f < data.run_config->minCoolingTemp) {
      p_f = data.run_config->minCoolingTemp * rho / (5.4e12*0.5);
    }

    Vc(i,j,k,PRS) = p_f;
    dE = fabs(1.0 - p_f/p) + 1.e-18;
    Dts.dt_cool = MIN(Dts.dt_cool, dt*data.run_config->maxCoolingRate/dE);
  }
}
