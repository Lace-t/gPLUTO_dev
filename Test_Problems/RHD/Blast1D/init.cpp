void Init (double *v, double x1, double x2, double x3, RunConfig &run_config)
/*!
*/
////////////////////////////////////////////////////////////////////////
{
  run_config.gamma = 1.4;

  v[RHO] = 1.0;
  v[VX1] = 0.0;
  v[VX2] = 0.0;
  v[VX3] = 0.0;
  v[TRC] = 0.0;
  
  if (x1<0.1){
    v[PRS] = 1.e3;
  }else if(x1<0.9) {
    v[PRS] = 1.e-2;
  }else {
    v[PRS] = 1.e2;
  }

}

