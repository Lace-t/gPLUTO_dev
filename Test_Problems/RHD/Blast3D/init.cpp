#include "gpluto.hpp"

////////////////////////////////////////////////////////////////////////
void Init (double *v, double x1, double x2, double x3, RunConfig &run_config)
/*
*/ 
////////////////////////////////////////////////////////////////////////
{
  double R, vol, r;
  double *inputParam = run_config.inputParam;

  // ---------------------------------------
  // compute region volume
  // ---------------------------------------

  R   = 0.5;
  vol = 4.0/3.0*CONST_PI*R*R*R;

  #if (GEOMETRY == SPHERICAL && DIMENSIONS == 1) || (GEOMETRY == SPHERICAL && DIMENSIONS == 3)

  r = x1*x1;

  #elif ((GEOMETRY == CYLINDRICAL) || (GEOMETRY == CARTESIAN)) && DIMENSIONS == 2

  r = x1*x1 + x2*x2;

  #elif (GEOMETRY == CARTESIAN && DIMENSIONS == 3)

  r = x1*x1 + x2*x2 + x3*x3;

  #else
  print ("! Init: geometrical configuration not allowed\n");
  QUIT_PLUTO(1);
  #endif

  r = sqrt(r);

  v[RHO] = inputParam[DNST0];
  v[VX1] = 0.0;
  v[VX2] = 0.0;
  v[VX3] = 0.0;
  
  #if EOS == IDEAL
  run_config.gamma = inputParam[GAMMA_EOS];
  #endif

  double gamma = 4./3.;

  if (r <= R)   v[PRS] = (gamma - 1.0)*inputParam[ENRG0]/vol;
  else          v[PRS] = 1.e-5;

}

